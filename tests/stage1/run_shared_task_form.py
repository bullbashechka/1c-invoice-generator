def client(port=6004):
    c = MCP(port)
    p = c.execute(PROBE)
    expected = json.loads((ROOT / '.local/stage-1/one-c-profile.json').read_text())['baseFingerprint']
    if p['baseFingerprint'] != expected:
        raise RuntimeError('DEMO_FINGERPRINT_MISMATCH')
    return c, p

def run_code(c, code, label, context='server'):
    result = c.rpc('tools/call', {'name': 'execute_code', 'arguments': {'code': code, 'execution_context': context}})
    (OUT / (label + '-private.json')).write_text(json.dumps(result, ensure_ascii=False), encoding='utf-8')
    answers = [json.loads(b['text']) for b in result.get('content', []) if b.get('type') == 'text']
    passed = len(answers) == 1 and answers[0].get('success') and not result.get('isError')
    print(json.dumps({'phase': label, 'passed': bool(passed), 'result': answers[0].get('data') if passed else 'FAILED_SEE_PRIVATE_RESULT'}, ensure_ascii=False), flush=True)
    return passed
